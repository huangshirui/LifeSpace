import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { parse } from "yaml";
const doc=parse(readFileSync(new URL("../mcp-operations.openapi.yaml",import.meta.url),"utf8"));
assert.equal(doc.openapi,"3.1.0");
assert.equal(doc.info.version,"0.6.0");
const get=doc.paths["/api/v1/spaces/{spaceId}/_discovery/operations"].get;
assert.deepEqual(get.parameters.filter(p=>p.in==="query").map(p=>p.name),["modelKey","operation","mode"]);
for(const p of get.parameters.filter(p=>p.in==="query"&&p.name!=="mode")) {
  assert.equal(p.required,false);
  assert.ok(new RegExp(p.schema.pattern).test(p.name==="modelKey"?"task":"action:complete"));
}
assert.deepEqual(get.parameters.find(p=>p.name==="mode").schema.enum,["delegation_request","configuration"]);
const catalog=get.responses["200"].content["application/json"].schema.properties.data.oneOf;
assert.deepEqual(catalog.map(c=>c.required[0]),["operations","eligibleOperations","configuredOperations"]);
const eligible=doc.components.schemas.DelegationEligibility;
assert.deepEqual(Object.keys(eligible.properties).sort(),["modelKey","operation","requiredScopes"]);
assert.equal(eligible.additionalProperties,false);
assert.ok(get.responses["400"]);
const descriptor=doc.components.schemas.OperationDescriptor;
assert.deepEqual(Object.keys(descriptor.properties).sort(),[...descriptor.required].sort());
assert.ok(new RegExp(descriptor.properties.operationRef.pattern).test("op_"+"a".repeat(64)));
assert.ok(doc.paths["/api/v1/spaces/{spaceId}/_operations/{operationRef}/invoke"].post);
assert.ok(new RegExp(descriptor.properties.operation.pattern).test("file_read"));
assert.ok(new RegExp(get.parameters.find(p=>p.name==="operation").schema.pattern).test("file_read"));
assert.ok(doc.paths["/api/v1/spaces/{spaceId}/models/{modelKey}/records/{recordId}/file-downloads"].post);
assert.ok(new RegExp(descriptor.properties.operation.pattern).test("file_upload"));
assert.ok(new RegExp(get.parameters.find(p=>p.name==="operation").schema.pattern).test("file_upload"));
assert.ok(doc.paths["/api/v1/spaces/{spaceId}/models/{modelKey}/file-uploads"].post);
assert.ok(doc.paths["/api/v1/spaces/{spaceId}/models/{modelKey}/file-uploads/{uploadId}/complete"].post);
console.log("Generic Operations OpenAPI syntax and target projection checks passed");
